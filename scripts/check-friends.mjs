import assert from 'node:assert/strict';
import { createEmptyState, inviteFriend, receiveFriendInvitation, respondFriendRequest, loadFriends, revokeFriendInvitation, sharedInteractions } from '../src/lib/friendsStore.js';

const storage = new Map();
globalThis.localStorage = { getItem: (key) => storage.get(key) || null, setItem: (key,value) => storage.set(key,value) };
const a = { id:'alice', name:'Alice' }, b = { id:'bob', name:'Bob' }, c = { id:'carol', name:'Carol' };
const state = createEmptyState(a);
assert.equal(state.experience,null);
assert.equal(state.participants.length,1);
const token = await inviteFriend(a,'demo','Bob');
await assert.rejects(() => receiveFriendInvitation(a,'demo',token));
const requestId = await receiveFriendInvitation(b,'demo',token);
assert.equal((await loadFriends(b,createEmptyState(b))).requests[0].sender.id,'alice');
assert.equal((await loadFriends(b,createEmptyState(b))).connections.length,0);
await respondFriendRequest(b,'demo',requestId,true);
await assert.rejects(() => receiveFriendInvitation(c,'demo',token));
assert.equal((await loadFriends(a,state)).connections[0].id,'bob');
assert.equal((await loadFriends(b,createEmptyState(b))).connections[0].id,'alice');
assert.equal((await loadFriends(c,createEmptyState(c))).connections.length,0);
const cancel = await inviteFriend(a,'demo','Cancel');
const pending = (await loadFriends(a,state)).invitations.find((entry) => entry.token === cancel);
await revokeFriendInvitation(a,'demo',pending.id);
await assert.rejects(() => receiveFriendInvitation(c,'demo',cancel));
const expired = await inviteFriend(a,'demo','Expired');
const raw = JSON.parse(storage.get('chippa-friends-v1'));
raw.invitations.find((entry) => entry.token === expired).expiresAt = '2000-01-01T00:00:00Z';
storage.set('chippa-friends-v1',JSON.stringify(raw));
await assert.rejects(() => receiveFriendInvitation(c,'demo',expired));
const meeting = { experience: {id:'test',date:'2026-11-16',invitationAccepted:true}, participants:[a,b], memberData:{ alice: { letters: [{id:'private',response:'SECRET',shared:false}], moment:{favorite:'SECRET',share:false,ready:true} } }, shared:{memories:[{id:'priv',text:'SECRET',shared:false},{id:'pub',text:'PUBLIC',shared:true}]} };
const interactions = sharedInteractions(meeting);
assert.equal(interactions.length,1);
assert.equal(interactions[0].text,'PUBLIC');
await loadFriends(c,{...createEmptyState(c),experienceArchives:[meeting]});
assert.equal((await loadFriends(c,createEmptyState(c))).connections.length,0);
console.log('OK: solicitudes mutuas, aprobación antes de conectar, tokens de un uso, auto-solicitud rechazada, revocación, vencimiento y privacidad entre perfiles.');
